def seed_taxonomy_if_empty(db):
    """
    Installs the base curriculum. These 10 topics are the foundation the learning
    loop builds on: they stay in rotation permanently and every AI-generated topic
    traces back to one of them.
    """
    from database.models import ContentTopic
    count = db.query(ContentTopic).count()
    if count == 0:
        created = []
        for topic_data in SEED_TOPICS:
            topic = ContentTopic(
                category=topic_data["category"],
                topic_key=topic_data["topic_key"],
                title=topic_data["title"],
                core_concept=topic_data["core_concept"],
                visual_blueprint=topic_data["visual_blueprint"],
                weight=topic_data["weight"],
                source="seed",
                is_active=True,
            )
            db.add(topic)
            created.append(topic)
        db.flush()
        # A base topic is its own base, so variants and bases group uniformly.
        for topic in created:
            topic.base_topic_id = topic.id
        db.commit()
